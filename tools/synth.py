#!/usr/bin/env python3
"""Generate a SYNTHETIC walk-away range test as JSONL, so the logger and dashboard can be tested without hardware.

Nothing in the output is real measurement data. Every file starts with a header marking it synthetic, and replaying it
marks the database session synthetic, which makes the dashboard show a banner.

Scenario: a base node (local, attached to the laptop) stays put; the peer walks away along a straight line at walking
pace and comes partway back. Link model: log-distance path loss (exponent 3.3, ground-level walk), 5 dB log-normal
shadowing, thermal noise floor for the preset, LoRa SNR saturating at +12 dB, and delivery probability falling off around
the SF11 demodulation limit (-17.5 dB). TETHER log lines mirror the firmware's format (docs/DESIGN_NOTES.md 7).

Usage: python tools/synth.py --out synthetic_walk.jsonl [--seed 7] [--minutes 50]
"""

import argparse
import json
import math
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tether_tools.parse import haversine_m  # noqa: E402

LOCAL_NUM = 0x0A0B0C0D
PEER_NUM = 0x1A2B3C4D  # higher than LOCAL_NUM, so the local node is the TETHER initiator
BASE_LAT, BASE_LON = 39.7392, -104.9903  # arbitrary point; the data is synthetic
TX_DBM = 22
NOISE_DBM = -174 + 10 * math.log10(250e3) + 6  # LongFast, NF 6 dB: about -114 dBm
SF, BW_KHZ = 11, 250
SNR_FLOOR = -17.5
SENS = NOISE_DBM + SNR_FLOOR
PING_MS = 12000


def nid(num: int) -> str:
    return "!%08x" % num


def offset(lat, lon, dist_m, bearing_deg):
    r = 6371008.8
    b = math.radians(bearing_deg)
    p1, l1 = math.radians(lat), math.radians(lon)
    p2 = math.asin(math.sin(p1) * math.cos(dist_m / r) + math.cos(p1) * math.sin(dist_m / r) * math.cos(b))
    l2 = l1 + math.atan2(math.sin(b) * math.sin(dist_m / r) * math.cos(p1), math.cos(dist_m / r) - math.sin(p1) * math.sin(p2))
    return math.degrees(p2), math.degrees(l2)


class Link:
    def __init__(self, rng: random.Random):
        self.rng = rng

    def sample(self, d_m: float):
        """One reception attempt at distance d: (received, rssi, snr)."""
        d = max(d_m, 1.0)
        path_loss = 31.7 + 10 * 3.3 * math.log10(d)  # 915 MHz free space at 1 m, then exponent 3.3
        signal = TX_DBM - path_loss + self.rng.gauss(0, 5.0)
        snr = signal - NOISE_DBM + self.rng.gauss(0, 0.8)
        p_ok = 1.0 / (1.0 + math.exp(-(snr - SNR_FLOOR - 1.0) / 1.2))
        if self.rng.random() > p_ok:
            return False, None, None
        # Packet RSSI includes noise power; reported SNR saturates.
        rssi = 10 * math.log10(10 ** (signal / 10) + 10 ** (NOISE_DBM / 10))
        return True, int(round(rssi)), round(max(min(snr, 12.0), -25.0) * 4) / 4


def margins(rssi, snr):
    return snr - SNR_FLOOR, rssi - SENS


def generate(seed: int = 7, minutes: float = 50.0, t0: float = 1762412400.0):
    rng = random.Random(seed)
    link = Link(rng)
    speed = 1.4  # m/s
    out_s = minutes * 60 * 0.7  # walk out for 70 % of the time, then back
    bearing = 60.0

    events = [{"type": "header", "synthetic": True, "generator": "tools/synth.py", "seed": seed,
               "note": "SYNTHETIC range test: generated by a link model, not measured"},
              {"type": "local_node", "t": t0, "id": nid(LOCAL_NUM)}]

    def peer_pos(t):
        el = t - t0
        d = speed * el if el <= out_s else max(0.0, speed * out_s - speed * (el - out_s))
        return offset(BASE_LAT, BASE_LON, d, bearing)

    def pkt(t, port, decoded, rx=None, from_num=PEER_NUM, to=0xFFFFFFFF, hops=3, pid=None):
        p = {"from": from_num, "to": to, "id": pid or rng.getrandbits(31), "channel": 0,
             "decoded": dict(decoded, portnum=port)}
        if rx:
            p.update({"rxRssi": rx[0], "rxSnr": rx[1], "hopStart": hops, "hopLimit": hops, "rxTime": int(t)})
        return {"type": "packet", "t": round(t, 3), "packet": p}

    def log(t, line):
        events.append({"type": "log", "t": round(t, 3), "line": line})

    end = t0 + minutes * 60
    seq = 0
    sent = replies = 0
    window = []
    next_ping, next_peer_pos, next_local_pos, next_text, next_stats = t0 + 30, t0 + 5, t0, t0 + 120, t0 + 60
    text_n = 0
    t = t0
    while t < end:
        t = min(next_ping, next_peer_pos, next_local_pos, next_text, next_stats)
        if t >= end:
            break
        lat, lon = peer_pos(t)
        d = haversine_m(BASE_LAT, BASE_LON, lat, lon)

        if t == next_local_pos:
            events.append(pkt(t, "POSITION_APP", {"position": {"latitude": BASE_LAT, "longitude": BASE_LON,
                                                               "altitude": 1609, "satsInView": 11, "PDOP": 120}},
                              from_num=LOCAL_NUM))
            next_local_pos += 60
        elif t == next_peer_pos:
            ok, rssi, snr = link.sample(d)
            if ok:
                events.append(pkt(t, "POSITION_APP", {"position": {"latitude": round(lat, 7), "longitude": round(lon, 7),
                                                                   "altitude": 1610, "satsInView": 9, "PDOP": 150}},
                                  rx=(rssi, snr)))
            next_peer_pos += 30
        elif t == next_text:
            ok, rssi, snr = link.sample(d)
            text_n += 1
            if ok:
                events.append(pkt(t, "TEXT_MESSAGE_APP", {"text": "checkpoint %d" % text_n}, rx=(rssi, snr)))
            next_text += 300
        elif t == next_stats:
            pdr = (sum(window) / len(window)) if window else 0.0
            log(t, "INFO  | [Tether] TETHER stats peer=%s role=initiator sent=%d replies=%d pdr32=%.2f window=%d "
                   "backoff=1 skipped=0 passive=0 rssi_ewma=na snr_ewma=na rpt_rssi_ewma=na rpt_snr_ewma=na"
                % (nid(PEER_NUM), sent, replies, pdr, len(window)))
            next_stats += 60
        else:  # ping
            ping_seq = seq
            seq += 1
            sent += 1
            line = "INFO  | [Tether] TETHER tx kind=ping peer=%s seq=%d interval_ms=%d airtime_ms=600 backoff=1" % (
                nid(PEER_NUM), ping_seq, PING_MS)
            log(t, line)
            ok_fwd, rssi_f, snr_f = link.sample(d)  # peer hears the ping
            ok_back = False
            if ok_fwd:
                ok_back, rssi_b, snr_b = link.sample(d)  # we hear the reply
            window = (window + [1 if ok_back else 0])[-32:]
            if ok_back:
                replies += 1
                tr = t + 1.3
                events.append(pkt(tr, "PRIVATE_APP", {}, rx=(rssi_b, snr_b), to=LOCAL_NUM, hops=0))
                ms, mr = margins(rssi_b, snr_b)
                log(tr, "INFO  | [Tether] TETHER rx kind=reply peer=%s seq=%d rssi=%d snr=%.2f margin_snr=%.2f "
                        "margin_rssi=%.1f" % (nid(PEER_NUM), ping_seq, rssi_b, snr_b, ms, mr))
                ms, mr = margins(rssi_f, snr_f)
                log(tr, "INFO  | [Tether] TETHER rpt kind=ping peer=%s seq=%d rssi=%d snr=%.2f margin_snr=%.2f "
                        "margin_rssi=%.1f" % (nid(PEER_NUM), ping_seq, rssi_f, snr_f, ms, mr))
            next_ping += PING_MS / 1000.0 * (0.9 + 0.2 * rng.random())

    head, body = events[:2], events[2:]
    body.sort(key=lambda e: e["t"])
    return head + body


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--minutes", type=float, default=50.0)
    args = ap.parse_args()
    events = generate(args.seed, args.minutes)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        for e in events:
            fh.write(json.dumps(e) + "\n")
    print("synth: wrote %d SYNTHETIC events to %s" % (len(events), args.out))


if __name__ == "__main__":
    main()
